    /**
     * Verifica si una matriz es diagonalmente dominante
     * Condición: |A[i][i]| >= Σ|A[i][j]| para j≠i, para todas las filas
     */
    private boolean verificarDominanciaDiagonal(Double[][] matrix, int filas) {
        for (int i = 0; i < filas; i++) {
            double diagonal = Math.abs(matrix[i][i]);
            double sumaFila = 0.0;
            
            for (int j = 0; j < matrix[i].length; j++) {
                if (i != j) {
                    sumaFila += Math.abs(matrix[i][j]);
                }
            }
            
            System.out.println("Fila " + (i+1) + ": |" + matrix[i][i] + "| = " + diagonal + 
                             " vs suma=" + sumaFila + " -> " + (diagonal >= sumaFila ? "✓" : "✗"));
            
            if (diagonal < sumaFila) {
                return false;
            }
        }
        return true;
    }
    
