    private void readMatrixFromFile(File file) throws IOException {
        List<Double[]> filas = new ArrayList<>();
        
        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            while ((line = br.readLine()) != null) {
                line = line.trim();
                if (line.isEmpty()) continue;
                
                // Limpiar la línea: remover caracteres no numéricos excepto espacios, puntos, signos y comas
                line = line.replaceAll("[^0-9.\\-+\\s,=]", " ");
                
                // Reemplazar múltiples espacios con uno solo
                line = line.replaceAll("\\s+", " ");
                
                // Dividir por espacios y/o comas
                String[] tokens = line.split("[\\s,=]+");
                
                List<Double> numerosEncontrados = new ArrayList<>();
                
                for (String token : tokens) {
                    token = token.trim();
                    if (!token.isEmpty()) {
                        try {
                            // Intentar convertir cada token a Double
                            if (token.matches("-?\\d+(\\.\\d+)?")) {
                                Double numero = Double.valueOf(token);
                                numerosEncontrados.add(numero);
                                //System.out.println("Número válido procesado: '" + token + "' -> " + numero);
                            } else {
                                System.out.println("Token rechazado (no es número): '" + token + "'");
                            }
                        } catch (NumberFormatException e) {
                            // Ignorar tokens que no se puedan convertir a números
                            System.out.println("Token ignorado: '" + token + "'");
                        }
                    }
                }

                if (!numerosEncontrados.isEmpty()) {
                    Double[] fila = numerosEncontrados.toArray(new Double[0]);
                    filas.add(fila);
                    //System.out.println("Fila procesada con " + fila.length + " números: " + Arrays.toString(fila));
                }
            }
        }

        // Convertir lista a matriz
        if (filas.isEmpty()) {
            throw new IOException("No se encontraron datos válidos en el archivo");
        }
        
        // Encontrar el número máximo de columnas
        int maxColumnas = 0;
        for (Double[] fila : filas) {
            maxColumnas = Math.max(maxColumnas, fila.length);
        }
        
        // Normalizar todas las filas al mismo tamaño rellenando con ceros
        for (int i = 0; i < filas.size(); i++) {
            if (filas.get(i).length < maxColumnas) {
                Double[] filaOriginal = filas.get(i);
                Double[] filaNormalizada = new Double[maxColumnas];
                
                // Copiar elementos existentes
                System.arraycopy(filaOriginal, 0, filaNormalizada, 0, filaOriginal.length);
                
                // Rellenar con ceros los elementos faltantes
                for (int j = filaOriginal.length; j < maxColumnas; j++) {
                    filaNormalizada[j] = 0.0;
                }
                
                filas.set(i, filaNormalizada);
                System.out.println("Fila " + (i+1) + " normalizada de " + filaOriginal.length + " a " + maxColumnas + " columnas");
            }
        }
        
        Double[][] matrizCarga = new Double[filas.size()][maxColumnas];
        for (int i = 0; i < filas.size(); i++) {
            matrizCarga[i] = filas.get(i);
        }
        
        if(btnCheckEliGauss.isSelected()){
            filasAlge = filas.size();
            columnasAlge = filas.get(0).length;
            this.matrixAlge = new Double[filasAlge][columnasAlge];
            this.matrixAAlge = new Double[filasAlge][columnasAlge - 1]; // Solo coeficientes A
            this.matrixBAlge = new Double[filasAlge];
            this.matrixXAlge = new Double[filasAlge];

            //System.out.println("Matriz Carga: \n"+printMatrix(matrizCarga));
            
            // Validar dimensiones antes de copiar
            for (int i = 0; i < filasAlge; i++) {
                int columnasToCopy = Math.min(matrizCarga[i].length, columnasAlge);
                System.arraycopy(matrizCarga[i], 0, this.matrixAlge[i], 0, columnasToCopy);
            }
            
            //System.out.println("Matriz Alge: \n"+printMatrix(matrixAlge));
        }
        if(btnCheckGaussSeidel.isSelected() || btnCheckJacobi.isSelected()){
            filasIte = filas.size();
            columnasIte = filas.get(0).length;
            this.matrixIte = new Double[filasIte][columnasIte];
            this.matrixAIte = new Double[filasIte][columnasIte - 1]; // Solo coeficientes A
            this.matrixBIte = new Double[filasIte];

            // Validar dimensiones antes de copiar
            for (int i = 0; i < filasIte; i++) {
                int columnasToCopy = Math.min(matrizCarga[i].length, columnasIte);
                System.arraycopy(matrizCarga[i], 0, this.matrixIte[i], 0, columnasToCopy);
            }
        }
    }

