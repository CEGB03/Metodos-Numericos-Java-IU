    private void separarMatricesAB(int columnas, int filas, Double[][] matrixA, Double[][] matrix, Double[] matrixB){
        int columns = columnas - 1; // Restar 1 para la matriz A (excluyendo la columna de términos independientes)
        
        // Validar que tenemos al menos 2 columnas (una para A y una para B)
        if (columnas < 2) {
            System.err.println("Error: La matriz debe tener al menos 2 columnas");
            return;
        }
        
        //System.out.println("columnas " + columnas + " filas " + filas + " columns " + columns);
        for (int i = 0; i < filas; i++) {
            // Copiar elementos de la matriz A
            for (int j = 0; j < columns && j < matrix[i].length; j++) {
                matrixA[i][j] = matrix[i][j];
            }
            // Copiar el término independiente (última columna)
            if (matrix[i].length >= columnas) {
                matrixB[i] = matrix[i][columnas - 1]; // Usar columnas - 1 para acceder a la última columna real
            } else {
                System.err.println("Error: Fila " + i + " no tiene suficientes columnas");
                matrixB[i] = 0.0; // Valor por defecto
            }
        }
        //imprimir();
    }
    
